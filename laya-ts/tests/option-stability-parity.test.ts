import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import {
  OptionStabilityHook,
  PredictContext,
  calibrateReliability,
  decideReliability,
  makeVariants,
  type CalibrationOptions,
  type OptionStabilityOptions,
  type OptionStabilityReport,
  type StabilityVariant,
  type VariantOptions,
} from "../src/index.js";
import { renderOptions } from "../src/common.js";

type Question = {
  type: "choice";
  instructions: string;
  criteria: string[] | Record<string, unknown>;
  option_order?: number[];
};
type Result = {
  answers: Record<string, {
    type: "choice";
    choice: string;
    probabilities: Record<string, number>;
    reliability?: OptionStabilityReport;
  }>;
  usage: Record<string, unknown>;
};
type HookCase = {
  name: string;
  states: unknown[];
  questions: Record<string, Question>;
  layout: "parallel" | "sequential";
  options: OptionStabilityOptions;
  expanded: { key: string; rendered: string[] }[];
  model_results: Result[];
  expected_results: Result[];
};
type Fixture = {
  schema: string;
  variant_cases: {
    name: string; labels: string[]; seed_key: string; options: VariantOptions; expected: StabilityVariant[];
  }[];
  hook_cases: HookCase[];
  calibration_cases: {
    name: string; scores: number[]; correct: boolean[]; options: CalibrationOptions;
    thresholds: [number, number]; decisions: (string | null)[];
  }[];
  decision_cases: { score: number; accept: number | null; escalate: number | null; expected: string | null }[];
  pipeline: {
    cases: string[]; correct: boolean[]; options: CalibrationOptions;
    thresholds: [number, number]; decisions: (string | null)[];
  };
};

// Generated by the actual Python hook and helpers, without model weights. The
// fixture records the exact reference commits and file hashes, including pending
// #1286/#1289 semantics. No Python installation is needed to run this TS suite.
const fixture = JSON.parse(readFileSync(new URL("../fixtures/option-stability.json", import.meta.url), "utf8")) as Fixture;

function physicalOptions(question: Question): string[] {
  const criteria = Array.isArray(question.criteria)
    ? Object.fromEntries(question.criteria.map((label) => [label, null]))
    : question.criteria;
  const rendered = renderOptions({ t: "choice", ins: question.instructions, crit: criteria });
  return (question.option_order ?? rendered.map((_, index) => index)).map((index) => rendered[index]);
}

function runHook(c: HookCase): Result[] {
  const questions = structuredClone(c.questions);
  const hook = new OptionStabilityHook(c.options);
  const context = new PredictContext({ states: structuredClone(c.states), questions,
    agent: { cfg: { option_layout: c.layout } } });
  hook.onPredictStart(context);
  expect(questions).toEqual(c.questions);
  // Compare what reaches each physical option slot. Integer-like JS object keys
  // reorder themselves, so raw criteria insertion order is not a valid oracle;
  // the TS hook uses option_order to realize the Python probe permutation.
  expect(Object.entries(context.questions).map(([key, q]) => ({ key, rendered: physicalOptions(q as Question) })))
    .toEqual(c.expanded);
  context.results = structuredClone(c.model_results);
  hook.onPredictEnd(context);
  expect(context.results).toEqual(c.expected_results);
  expect(questions).toEqual(c.questions);
  // A completed plan must be consumed, so a repeated end event cannot apply the
  // same mapping to already-cleaned output or produce an unprobed report.
  hook.onPredictEnd(context);
  expect(context.results).toEqual(c.expected_results);
  return context.results as Result[];
}

describe("Python option stability fixtures", () => {
  it("uses the supported fixture schema", () => {
    expect(fixture.schema).toBe("laya-option-stability/1");
  });

  describe("CRC32 / Python integer-seeded shuffle / filtering / deduplication", () => {
    for (const c of fixture.variant_cases) {
      it(c.name, () => {
        const labels = [...c.labels];
        expect(makeVariants(labels, c.seed_key, c.options)).toEqual(c.expected);
        expect(labels).toEqual(c.labels);
        expect(makeVariants(labels, c.seed_key, c.options)).toEqual(c.expected);
      });
    }
  });

  describe("expanded semantics, label mapping, reporting and cleanup", () => {
    for (const c of fixture.hook_cases) {
      it(c.name, () => {
        const results = runHook(c);
        for (const result of results) {
          const report = result.answers.q.reliability!;
          if (report.soft_stability === null) {
            expect(report.decision).toBeNull();
            expect(report.probes).toEqual([]);
          } else {
            // Use the persisted public score, not rounded variant_support or an
            // independently reconstructed mean, to replay the actual decision.
            const saved = JSON.parse(JSON.stringify(report)) as OptionStabilityReport;
            expect(decideReliability(saved.soft_stability!, c.options.accept, c.options.escalate))
              .toBe(report.decision);
          }
        }
      });
    }
  });

  describe("raw calibration cohorts and boundary replay", () => {
    for (const c of fixture.calibration_cases) {
      it(c.name, () => {
        const thresholds = calibrateReliability(c.scores, c.correct, c.options);
        expect(thresholds).toEqual(c.thresholds);
        expect(c.scores.map((score) => decideReliability(score, ...thresholds))).toEqual(c.decisions);
      });
    }
    it("matches all categorical boundaries, including adjacent representable numbers", () => {
      for (const c of fixture.decision_cases) {
        expect(decideReliability(c.score, c.accept, c.escalate)).toBe(c.expected);
      }
    });
    it("fits the persisted runtime reports and retains cuts that share four decimal digits", () => {
      const pipeline = fixture.pipeline;
      const scores = pipeline.cases.map((name) => {
        const c = fixture.hook_cases.find((item) => item.name === name)!;
        return runHook(c)[0].answers.q.reliability!.soft_stability!;
      });
      expect(new Set(scores).size).toBe(3);
      const savedScores = JSON.parse(JSON.stringify(scores)) as number[];
      const thresholds = calibrateReliability(savedScores, pipeline.correct, pipeline.options);
      expect(thresholds).toEqual(pipeline.thresholds);
      expect(savedScores.map((score) => decideReliability(score, ...thresholds))).toEqual(pipeline.decisions);
    });
  });
});
